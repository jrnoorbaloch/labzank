/**
 * Generates supabase/seed.sql from the app's local sample data, so the
 * database starts with exactly what the static site shows.
 *   npx tsx scripts/gen-seed.ts
 */
import { writeFileSync } from "node:fs";
import { entries, sources, wordOfDaySchedule } from "../src/lib/dictionary/data";
import { audio, books, events, folk, heroSlides, poems, poets } from "../src/lib/content";
import { DEFAULT_SECTIONS, SECTION_KEYS } from "../src/lib/sections";

const q = (s: string | undefined | null) => (s == null || s === "" ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const j = (v: unknown) => (v == null ? "null" : `${q(JSON.stringify(v))}::jsonb`);
const arr = (a?: string[]) => (a && a.length ? `array[${a.map(q).join(",")}]::text[]` : "null");
const out: string[] = ["-- generated by scripts/gen-seed.ts — do not edit by hand", "begin;", ""];

/* ── content ── */
out.push("-- authors (bios are short; an editor should verify and expand)");
poets.forEach((p, i) =>
  out.push(`insert into public.authors (slug, name, period, years, place, bio, works, hue, featured, sort, status) values (${q(p.slug)}, ${j(p.name)}, ${q(p.period)}, ${q(p.years)}, ${j(p.place)}, ${j(p.bio)}, ${p.works}, ${p.hue}, ${i === 2}, ${i}, 'published');`)
);
out.push("", "-- poems: ORIGINAL placeholder verses credited to demo contributors");
poems.forEach((p, i) =>
  out.push(`insert into public.poems (slug, form, original, roman, translation, contributor, is_sample, featured, sort, status, published_at) values (${q(p.id)}, ${j(p.form)}, ${q(p.original)}, ${q(p.roman)}, ${j(p.translation)}, ${j(p.contributor)}, true, true, ${i}, 'published', now());`)
);
out.push("");
books.forEach((b, i) =>
  out.push(`insert into public.books (slug, title, author_text, author_id, cat, pages, year, palette, is_demo, sort, status) values (${q(b.id)}, ${j(b.title)}, ${j(b.author)}, ${b.authorSlug ? `(select id from public.authors where slug = ${q(b.authorSlug)})` : "null"}, ${q(b.cat)}, ${b.pages}, ${q(b.year)}, ${arr(b.palette)}, ${!!b.demo}, ${i}, 'published');`)
);
out.push("");
events.forEach((e, i) => out.push(`insert into public.events (day, month, title, place, sort, status) values (${q(e.day)}, ${j(e.month)}, ${j(e.title)}, ${j(e.place)}, ${i}, 'published');`));
folk.forEach((f, i) => out.push(`insert into public.folk_items (title, body, glyph, sort, status) values (${j(f.title)}, ${j(f.body)}, ${q(f.glyph)}, ${i}, 'published');`));
audio.forEach((a, i) => out.push(`insert into public.audio_items (title, by_line, duration, sort, status) values (${j(a.title)}, ${j(a.by)}, ${q(a.dur)}, ${i}, 'published');`));
heroSlides.forEach((h, i) =>
  out.push(`insert into public.hero_slides (heading, description, cta, sort) values (${j(h.heading)}, ${j(h.description)}, ${j(h.cta ? [h.cta] : [])}, ${i});`)
);
out.push("");
// Rekhta-style default order; manifesto, stats and cta start hidden (switch on in Admin → Homepage builder)
SECTION_KEYS.forEach((k, i) =>
  out.push(`insert into public.homepage_sections (key, enabled, sort) values (${q(k)}, ${DEFAULT_SECTIONS.includes(k)}, ${(i + 1) * 10});`)
);

/* ── dictionary ── */
out.push("", "-- dictionary: 30 ORIGINAL sample entries, status draft (not Labzganj data)");
for (const [id, s] of Object.entries(sources))
  out.push(`insert into public.dict_sources (id, name, licence, attribution, url) values (${q(id)}, ${q(s.name)}, ${q(s.licence)}, ${q(s.attribution)}, ${q(s.url)});`);
const sel = (slug: string) => `(select id from public.dict_entries where slug = ${q(slug)})`;
for (const e of entries) {
  out.push(`insert into public.dict_entries (slug, headword_arab, headword_latn, word_type, status, source_id, created_at) values (${q(e.slug)}, ${q(e.arab)}, ${q(e.latn)}, ${q(e.type)}, ${q(e.status === "pending" ? "pending_review" : e.status)}, ${q(e.source)}, ${q(e.added)}::timestamptz);`);
  if (e.ipa || e.syllables) out.push(`insert into public.dict_pronunciations (entry_id, ipa, syllables) values (${sel(e.slug)}, ${q(e.ipa)}, ${arr(e.syllables)});`);
  e.senses.forEach((s, i) => {
    const sid = `(select id from public.dict_senses where entry_id = ${sel(e.slug)} and n = ${i + 1})`;
    out.push(`insert into public.dict_senses (entry_id, n, pos) values (${sel(e.slug)}, ${i + 1}, ${q(s.pos)});`);
    for (const [lang, text] of Object.entries(s.gloss)) out.push(`insert into public.dict_glosses (sense_id, lang, text) values (${sid}, ${q(lang)}, ${q(text)});`);
    for (const x of s.examples ?? []) {
      out.push(`with x as (insert into public.dict_examples (sense_id, text_arab, text_latn, source_id) values (${sid}, ${q(x.arab)}, ${q(x.latn)}, ${q(e.source)}) returning id)`);
      const tr = [["en", x.en], ["ur", x.ur]].filter(([, v]) => v);
      out.push(tr.length ? `insert into public.dict_example_translations (example_id, lang, text) select x.id, v.lang, v.text from x, (values ${tr.map(([l, v]) => `(${q(l)}, ${q(v)})`).join(", ")}) v(lang, text);` : "select 1 from x;");
    }
  });
}
for (const e of entries) {
  if (e.root) out.push(`update public.dict_entries set root_entry_id = ${sel(e.root)} where slug = ${q(e.slug)};`);
  for (const r of e.relations ?? []) out.push(`insert into public.dict_relations (from_entry, to_entry, type) values (${sel(e.slug)}, ${sel(r.to)}, ${q(r.type)}) on conflict do nothing;`);
}
for (const w of wordOfDaySchedule) out.push(`insert into public.dict_word_of_day (day, entry_id) values (${q(w.date)}, ${sel(w.slug)});`);
out.push("", "commit;", "");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(`seed.sql: ${out.length} lines`);
